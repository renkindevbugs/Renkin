internal data class GlobalModifierSnapshot(
    val primarySource: Source,
    val primaryIconPack: String,
    val secondarySource: Source,
    val secondaryIconPack: String,
    val fallbackSource: FallbackSource,
    val modifiers: ModifierStack,
    val applyGenerated: Boolean,
    val applyExisting: Boolean,
    val applyCustom: Boolean,
    val includeEmpty: Boolean
)

@Stable
internal class GlobalModifierState {
    var initialized by mutableStateOf(false)
        private set
    var primarySource by mutableStateOf(SOURCE_DEFAULT)
    var primaryIconPack by mutableStateOf("")
    var secondarySource by mutableStateOf(SOURCE_DEFAULT)
    var secondaryIconPack by mutableStateOf("")
    var fallbackSource by mutableStateOf(FALLBACK_SOURCE_DEFAULT)
    var modifiers by mutableStateOf(defaultGlobalModifiers())
        private set
    var applyGenerated by mutableStateOf(true)
    var applyExisting by mutableStateOf(false)
    var applyCustom by mutableStateOf(false)
    var includeEmpty by mutableStateOf(false)

    // Both groups and their styles remain configured while disabled, so toggles retain drafts.
    val shape: ShapeModifier get() = requireNotNull(modifiers.shape)
    val outline: OutlineModifier get() = requireNotNull(modifiers.outline)
    val hasAnyEffect: Boolean get() = modifiers.hasVisibleEffect

    fun updateEffect(update: EffectModifier.() -> EffectModifier) {
        modifiers = modifiers.copy(effect = modifiers.effect.update()).withNormalizedGlobalColorizer()
    }

    fun updateTransform(update: TransformModifier.() -> TransformModifier) {
        modifiers = modifiers.copy(transform = modifiers.transform.update())
    }

    fun updateShape(update: ShapeModifier.() -> ShapeModifier) {
        modifiers = modifiers.copy(shape = shape.update()).withGlobalDraftDefaults()
    }

    fun updateOutline(update: OutlineModifier.() -> OutlineModifier) {
        modifiers = modifiers.copy(outline = outline.update()).withGlobalDraftDefaults()
    }

    fun seedFrom(preferences: Preferences) {
        primarySource = Source.entries.getOrElse(
            preferences.getIntValue(PrimarySourceKey, SOURCE_DEFAULT.ordinal)
        ) { SOURCE_DEFAULT }
        primaryIconPack = preferences.getStringValue(PrimaryIconPackKey)
        secondarySource = Source.entries.getOrElse(
            preferences.getIntValue(SecondarySourceKey, SOURCE_DEFAULT.ordinal)
        ) { SOURCE_DEFAULT }
        secondaryIconPack = preferences.getStringValue(SecondaryIconPackKey)
        fallbackSource = FallbackSource.entries.getOrElse(
            preferences.getIntValue(FallbackSourceKey, FALLBACK_SOURCE_DEFAULT.ordinal)
        ) { FALLBACK_SOURCE_DEFAULT }
        val loaded = globalModifierOptions(preferences).modifiers.withGlobalDraftDefaults()
        modifiers = loaded.copy(
            shape = requireNotNull(loaded.shape).copy(
                fill = preferences.colorStyle(GlobalShapeStyleKeys, Color.White).asFill()
            )
        )
        applyGenerated = preferences.getBooleanValue(GlobalApplyGeneratedKey, true)
        applyExisting = preferences.getBooleanValue(GlobalApplyExistingKey)
        applyCustom = preferences.getBooleanValue(GlobalApplyCustomKey)
        includeEmpty = preferences.getBooleanValue(GlobalIncludeEmptyKey)
        initialized = true
    }

    fun snapshot() = GlobalModifierSnapshot(
        primarySource = primarySource,
        primaryIconPack = primaryIconPack,
        secondarySource = secondarySource,
        secondaryIconPack = secondaryIconPack,
        fallbackSource = fallbackSource,
        modifiers = modifiers.copy(
            effect = modifiers.effect.copy(colorizer = modifiers.effect.colorizer.normalizedFlags().roundedForSnapshot()),
            transform = modifiers.transform.copy(scale = modifiers.transform.scale.roundedGlobalScale()),
            shape = shape.copy(scale = shape.scale.roundedGlobalScale(), fill = shape.fill?.roundedForSnapshot()),
            outline = outline.copy(width = outline.width.roundToInt().toFloat(), fill = outline.fill.roundedForSnapshot())
        ),
        applyGenerated = applyGenerated,
        applyExisting = applyExisting,
        applyCustom = applyCustom,
        includeEmpty = includeEmpty
    )

    fun restore(snapshot: GlobalModifierSnapshot) {
        primarySource = snapshot.primarySource
        primaryIconPack = snapshot.primaryIconPack
        secondarySource = snapshot.secondarySource
        secondaryIconPack = snapshot.secondaryIconPack
        fallbackSource = snapshot.fallbackSource
        modifiers = snapshot.modifiers.withGlobalDraftDefaults().withNormalizedGlobalColorizer()
        applyGenerated = snapshot.applyGenerated
        applyExisting = snapshot.applyExisting
        applyCustom = snapshot.applyCustom
        includeEmpty = snapshot.includeEmpty
        initialized = true
    }

    fun overlay(preferences: Preferences): Preferences =
        preferences.toMutablePreferences().also { writeInto(it) }

    private fun writeInto(mutable: MutablePreferences) {
        mutable[PrimarySourceKey] = primarySource.ordinal
        mutable[PrimaryIconPackKey] = primaryIconPack
        mutable[SecondarySourceKey] = secondarySource.ordinal
        mutable[SecondaryIconPackKey] = secondaryIconPack
        mutable[FallbackSourceKey] = fallbackSource.ordinal
        mutable[GlobalShapeKey] = shape.shape.ordinal
        mutable[GlobalShapeCropKey] = shape.crop
        mutable[GlobalShapeScaleKey] = (shape.scale * 100).roundToInt()
        mutable.writeColorStyle(GlobalShapeStyleKeys, requireNotNull(shape.fill?.style))
        mutable[GlobalIconScaleKey] = (modifiers.transform.scale * 100).roundToInt()
        mutable[OutlineAddKey] = outline.isEnabled
        mutable[OutlineWidthKey] = outline.width.roundToInt()
        mutable.writeColorStyle(OutlineStyleKeys, requireNotNull(outline.fill.style))
        val effect = modifiers.effect
        val colorizer = effect.colorizer.normalizedFlags()
        mutable[GlobalColorizeKey] = effect.imageEdit == ImageEdit.COLORIZE
        mutable.writeColorStyle(GlobalColorizerStyleKeys, colorizer)
        mutable[GlobalColorizeFlatKey] = colorizer.flat
        mutable[GlobalColorizeLightenKey] = colorizer.lighten
        mutable[GlobalColorizeMonochromeKey] = colorizer.monochrome
        mutable[GlobalColorizeInverseKey] = colorizer.inverse
        mutable[GlobalApplyGeneratedKey] = applyGenerated
        mutable[GlobalApplyExistingKey] = applyExisting
        mutable[GlobalApplyCustomKey] = applyCustom
        mutable[GlobalIncludeEmptyKey] = includeEmpty
    }

    // Preview and Save use the same preference precision and normalization as a later refresh.
    fun toModifierOptions(): GenerationOptions = globalModifierOptions(overlay(emptyPreferences()))

    companion object {
        val Saver = GlobalModifierStateSaver
        val BaselineSaver = GlobalModifierBaselineSaver
    }
}

private fun defaultGlobalModifiers() = ModifierStack(
    effect = EffectModifier(ImageEdit.NONE, ColorizerStyle(firstColor = android.graphics.Color.WHITE)),
    shape = defaultGlobalShape,
    outline = defaultGlobalOutline
)

private val defaultGlobalShape = ShapeModifier(
    IconShape.NONE, true, 1f, ColorizerStyle(firstColor = android.graphics.Color.WHITE).asFill()
)
private val defaultGlobalOutline = OutlineModifier(
    OutlineMode.NONE, OUTLINE_WIDTH_DEFAULT.toFloat(), ColorizerStyle(firstColor = android.graphics.Color.BLACK).asFill()
)

internal fun ModifierStack.withGlobalDraftDefaults(): ModifierStack {
    val shape = shape ?: defaultGlobalShape
    val shapeFill = shape.fill ?: requireNotNull(defaultGlobalShape.fill)
    val outline = outline ?: defaultGlobalOutline
    return copy(
        shape = shape.copy(fill = shapeFill.withStyleFallback()),
        outline = outline.copy(fill = outline.fill.withStyleFallback())
    )
}

internal fun ModifierStack.withNormalizedGlobalColorizer(): ModifierStack =
    withEffect { copy(colorizer = colorizer.normalizedFlags()) }

private fun ColorFill.withStyleFallback(): ColorFill =
    if (style != null) this else ColorizerStyle(firstColor = color).asFill()

internal fun ColorizerStyle.asFill(): ColorFill = ColorFill(firstColor, this)

private fun Float.roundedGlobalScale(): Float = (this * 100).roundToInt() / 100f
private fun ColorizerStyle.roundedForSnapshot(): ColorizerStyle = copy(gradientAngle = gradientAngle.roundToInt().toFloat())
private fun ColorFill.roundedForSnapshot(): ColorFill = copy(style = style?.roundedForSnapshot())

private fun MutablePreferences.writeColorStyle(keys: ColorStyleKeys, style: ColorizerStyle) {
    setColorStyle(
        keys = keys,
        mode = style.mode.ordinal,
        gradientType = style.gradientType.ordinal,
        gradientAngle = style.gradientAngle.roundToInt(),
        firstColor = Color(style.firstColor),
        gradientStops = style.gradientStops,
        gradientPositions = style.gradientPositions
    )
}
